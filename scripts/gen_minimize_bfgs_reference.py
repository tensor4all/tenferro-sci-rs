def _mv(H, v):  # left-to-right summation, the order BLAS does not use
    return [sum(H[i][j] * v[j] for j in range(len(v))) for i in range(len(v))]


def mirror(spec: Spec, log: Log, n_updates_limit=None):
    """Replay SciPy's recorded (f, g) through a plain-Python BFGS and measure |x_mirror - x_SciPy| / (n eps S).

    The mirror does what the Rust replay does: it feeds SciPy's recorded f and g, computes its own p = -H g,
    phi' = g . p, the step through SciPy's own ``scalar_search_wolfe1``, and the update. Returns the
    per-evaluation scales, ratios, and the direction ratios against the mpmath direction.
    """
    n = len(spec.x0)
    ev = log.evals
    H = [[1.0 if i == j else 0.0 for j in range(n)] for i in range(n)]
    pairs = []
    x = [float(t) for t in spec.x0]
    g = list(ev[0][2])
    f = ev[0][1]
    f_old = f + float(np.linalg.norm(ev[0][2])) / 2.0
    idx = 1
    scales = {}  # evaluation index -> scale vector
    ratios = {}
    envs = {}
    dir_info = []  # per line search: (mirror p, exact-direction ratio computed later)
    Hbar = np.eye(n)
    for rec in log.ls:
        if rec["failed"] or rec["w2"] is not None:
            break
        p = [-t for t in _mv(H, g)]
        pbar = Hbar @ np.abs(np.array(g))
        dir_info.append((list(p), pbar.copy()))
        xk = list(x)
        state = {"i": idx}

        def phi(a, xk=xk, p=p, state=state, pbar=pbar):
            i = state["i"]
            xr = [xk[j] + a * p[j] for j in range(n)]
            S = np.abs(np.array(xk)) + abs(a) * pbar
            scales[i] = S
            err = np.abs(np.array(xr) - ev[i][0])
            ratios[i] = float(np.max(err / (n * EPS * np.maximum(S, np.finfo(float).tiny))))
            envs[i] = float(np.max(err)) / (1.0 + float(np.max(np.abs(ev[i][0]))))
            return ev[i][1]

        def dphi(a, p=p, state=state):
            i = state["i"]
            d = sum(ev[i][2][j] * p[j] for j in range(n))
            state["i"] = i + 1
            return d

        derphi0 = sum(g[j] * p[j] for j in range(n))
        alpha, phi1, _ = lsm.scalar_search_wolfe1(phi, dphi, f, f_old, derphi0, c1=spec.c1, c2=spec.c2,
                                                  amax=1e100, amin=1e-100, xtol=1e-14)
        if alpha is None:
            break
        i_last = state["i"] - 1
        s = [alpha * t for t in p]
        x = [x[j] + s[j] for j in range(n)]
        g_new = list(ev[i_last][2])
        y = [g_new[j] - g[j] for j in range(n)]
        f_old, f = f, phi1
        g = g_new
        idx = state["i"]
        gn = max(abs(t) for t in g)
        pn = math.sqrt(sum(t * t for t in p))
        xn = math.sqrt(sum(t * t for t in x))
        if gn <= spec.gtol or alpha * pn <= spec.xrtol * (spec.xrtol + xn) or not math.isfinite(f):
            break
        # update, Optim-style symmetric form: H += c1 s s^T - rho (u s^T + s u^T), u = H y
        sy = sum(s[j] * y[j] for j in range(n))
        rho = 1.0 / sy
        u = _mv(H, y)
        c1 = rho + rho * rho * sum(y[j] * u[j] for j in range(n))
        H = [[H[i][j] + c1 * s[i] * s[j] - rho * (u[i] * s[j] + s[i] * u[j]) for j in range(n)] for i in range(n)]
        pairs.append((s, y))
        Hbar = scale_updates(n, [(np.array(a), np.array(b)) for a, b in pairs])[-1]
    return scales, ratios, envs, dir_info, H


