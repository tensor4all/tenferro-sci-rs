def render(out):
    texts = {}
    for key, cols in COLUMNS.items():
        lines = [HEADER.rstrip("\n"), ",".join(cols)]
        for row in out[key]:
            cells = [str(row[c]) for c in cols]
            for c in cells:
                assert "," not in c and '"' not in c, (key, c)
            lines.append(",".join(cells))
        texts[FILES[key]] = "\n".join(lines) + "\n"
    return texts


def assert_derivation(stats):
    """The README's tolerances, confirmed on the data: refuse to write data that violates them with margin."""
    limit = REPLAY_C / MARGIN
    env_limit = ENVELOPE / MARGIN
    print(f"strict scale (C = {REPLAY_C:g}): measured |error| / (n eps scale) evals {stats['ratio_max']:.3g}, "
          f"directions {stats['dir_ratio_max']:.3g}, final H {stats['hess_ratio_max']:.3g}; limit {limit:g}")
    print(f"envelope ({ENVELOPE:g}): measured evals {stats['env_max']:.3g} (relative to 1 + |x|inf), "
          f"directions {stats['dir_env_max']:.3g} (relative to |d|inf), final H {stats['hess_env_max']:.3g}; "
          f"limit {env_limit:g}")
    bad = [k for k in ("ratio_max", "dir_ratio_max", "hess_ratio_max") if stats[k] > limit] + \
          [k for k in ("env_max", "dir_env_max", "hess_env_max") if stats[k] > env_limit]
    if bad:
        print(f"the documented tolerances do not hold with margin ({', '.join(bad)}): refusing", file=sys.stderr)
        sys.exit(1)


