# Exact (mpmath) BFGS inverse Hessian from SciPy's pairs, and the absolute-value scale recursion
# ----------------------------------------------------------------------------------------------

mpmath.mp.dps = 60


def mp_updates(n, pairs):
    """H_k as mpf matrices for k = 0..len(pairs), H_0 = I, SciPy's recursion in exact arithmetic."""
    H = mpmath.eye(n)
    out = [H.copy()]
    for s, y in pairs:
        sm, ym = mpmath.matrix([mpmath.mpf(float(t)) for t in s]), mpmath.matrix([mpmath.mpf(float(t)) for t in y])
        rho = 1 / (ym.T * sm)[0]
        I = mpmath.eye(n)
        A1 = I - rho * sm * ym.T
        A2 = I - rho * ym * sm.T
        H = A1 * H * A2 + rho * sm * sm.T
        out.append(H.copy())
    return out


def scale_updates(n, pairs):
    """Absolute-value scales of the rounding of H_k, k = 0..len(pairs), in float64.

    The sum of two recursions, one per formula that computes the update:

    * SciPy's form  H' = (I - rho s y^T) H (I - rho y s^T) + rho s s^T:
      Ha' = |A1| Ha |A2| + |rho| |s||s|^T,
    * the symmetric form  H' = H + c s s^T - rho (u s^T + s u^T),  u = H y,  c = rho + rho^2 y^T u
      (what the Rust implementation is written as):
      Hs' = Hs + |c| |s||s|^T + |rho| (|u||s|^T + |s||u|^T),  |u| = Hs |y|,  |c| = |rho| + rho^2 |y|^T |u|.

    The requested point of one implementation is compared with the other's, so both enter.
    """
    Ha = np.eye(n)
    Hs = np.eye(n)
    out = [Ha + Hs]
    I = np.eye(n)
    for s, y in pairs:
        s, y = np.asarray(s, dtype=float), np.asarray(y, dtype=float)
        rho = abs(1.0 / float(np.dot(y, s)))
        A1 = np.abs(I - rho * np.outer(s, y))
        A2 = np.abs(I - rho * np.outer(y, s))
        Ha = A1 @ Ha @ A2 + rho * np.outer(np.abs(s), np.abs(s))
        u = Hs @ np.abs(y)
        c = rho + rho * rho * float(np.abs(y) @ u)
        Hs = Hs + c * np.outer(np.abs(s), np.abs(s)) + rho * (np.outer(u, np.abs(s)) + np.outer(np.abs(s), u))
        out.append(Ha + Hs)
    return out


