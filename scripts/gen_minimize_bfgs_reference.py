def fl(x) -> str:
    if x is None:
        return "none"
    x = float(x)
    if math.isnan(x):
        return "nan"
    if math.isinf(x):
        return "inf" if x > 0 else "-inf"
    return repr(x)


def vec(v) -> str:
    return ";".join(fl(t) for t in np.asarray(v, dtype=float).ravel())


def clean(s: str) -> str:
    return str(s).replace(",", " ").replace('"', "'").replace("\n", " ").strip()


