# A hand-fed scenario with a line search that ends in a dcsrch WARNING
# ----------------------------------------------------------------------------------------------

# (f, g) the objective returns at the k-th evaluation (the values need not come from one function; the optimizer
# sees only these numbers). x0 = [0], so the first search starts with d = -g = [1] and step 1/|d| = 1. Trial 1
# satisfies the sufficient decrease but not the curvature condition (|g| = 0.95 > 0.9 |g0|), trial 2 overshoots, the
# bracket [1, 5] shrinks until dcsrch ends with "WARNING: XTOL TEST SATISFIED" at a trial with f = 10 > f0 = 4.
# lnsrlb accepts a warning like a convergence (task NEW_X at the last trial), so the iterate is x = [1] with f = 10,
# and the one-sided test (f_old - f) <= ftol max(|f_old|, |f|, 1) stops the run with FTol. A two-sided test would not.
SCRIPT = [(4.0, [-1.0]), (3.5, [-0.95])] + [(10.0, [1.0])] * 4
SCRIPT_OPTIONS = dict(maxcor=10, gtol=1e-12, ftol=0.25, maxfun=15000, maxiter=15000, maxls=40)
SCRIPT_REQUESTS = [0.0, 1.0, 5.0, 1.3552244689139858, 1.0030498702469033, 1.0]


def scripted_checks():
    calls: list[float] = []

    def fun(x):
        k = len(calls)
        calls.append(float(x[0]))
        f, g = SCRIPT[k]
        return f, np.array(g)

    r = so.minimize(fun, np.array([0.0]), jac=True, method="L-BFGS-B", bounds=None, options=dict(SCRIPT_OPTIONS))
    assert calls == SCRIPT_REQUESTS, calls
    assert r.status == 0 and r.message == "CONVERGENCE: RELATIVE REDUCTION OF F <= FACTR*EPSMCH", r.message
    assert (r.nit, r.nfev, float(r.x[0]), float(r.fun)) == (1, 6, 1.0, 10.0)
    # the mirror (accept at the last trial, one-sided ftol) agrees
    M = Mirror([0.0], SCRIPT_OPTIONS["maxcor"], 1e-12, 0.25, 15000, 15000, 40)
    x, asked = M.req, [float(M.req[0])]
    for f, g in SCRIPT:
        x = M.tell(f, np.array(g))
        if x is None:
            break
        asked.append(float(x[0]))
    assert asked == SCRIPT_REQUESTS and M.term == "f_tol" and M.task.startswith(b"WARNING: XTOL"), (asked, M.term, M.task)
    print("  scripted XTOL-warning case: SciPy and the mirror agree")

