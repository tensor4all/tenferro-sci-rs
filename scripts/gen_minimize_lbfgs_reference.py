def mp_vec(v):
    return [mpmath.mpf(float(t)) for t in v]


def mp_dot(a, b):
    return mpmath.fsum(x * y for x, y in zip(a, b))


def exact_direction(S, Y, g):
    """-H g by the two-loop recursion in 60-digit arithmetic from the stored pairs (oldest first),
    with H0 = gamma I, gamma = s^T y / y^T y of the newest pair (computed exactly), together with
    the absolute-value recursion (Higham, section 3.1) that gives the scale S_i = sum |terms|
    of component i. No pairs: d = -g, scale |g|."""
    n = len(g)
    if not S:
        return [float(-t) for t in g], [abs(float(t)) for t in g], 1.0
    Sm = [mp_vec(s) for s in S]
    Ym = [mp_vec(y) for y in Y]
    gm = mp_vec(g)
    rho = [1 / mp_dot(y, s) for s, y in zip(Sm, Ym)]
    gamma = mp_dot(Sm[-1], Ym[-1]) / mp_dot(Ym[-1], Ym[-1])
    q = list(gm)
    qa = [abs(t) for t in gm]
    alpha, alpha_a = [], []
    for i in reversed(range(len(Sm))):
        a = rho[i] * mp_dot(Sm[i], q)
        aa = abs(rho[i]) * mp_dot([abs(t) for t in Sm[i]], qa)
        q = [qi - a * yi for qi, yi in zip(q, Ym[i])]
        qa = [qi + aa * abs(yi) for qi, yi in zip(qa, Ym[i])]
        alpha.append(a)
        alpha_a.append(aa)
    alpha.reverse()
    alpha_a.reverse()
    r = [gamma * t for t in q]
    ra = [abs(gamma) * t for t in qa]
    for i in range(len(Sm)):
        b = rho[i] * mp_dot(Ym[i], r)
        ba = abs(rho[i]) * mp_dot([abs(t) for t in Ym[i]], ra)
        r = [ri + si * (alpha[i] - b) for ri, si in zip(r, Sm[i])]
        ra = [ri + abs(si) * (alpha_a[i] + ba) for ri, si in zip(ra, Sm[i])]
    return [float(-t) for t in r], [float(t) for t in ra], float(gamma)



# ----------------------------------------------------------------------------------------------
# A float64 mirror of the algorithm the Rust implementation follows (README.md, "How the tolerance
# was derived"). It exists only to measure how far an independent float64 implementation that
# replays SciPy's (f, g) can drift from SciPy's requested points, so that the replay tolerance
# is derived from data and not guessed. The Rust code is written independently of it.
# ----------------------------------------------------------------------------------------------


class Mirror:
    def __init__(self, x0, m, gtol, ftol, maxiter, maxfun, maxls):
        self.m, self.gtol, self.maxiter, self.maxfun, self.maxls = m, gtol, maxiter, maxfun, maxls
        self.tol = (ftol / EPS) * EPS  # SciPy: tol = factr * epsmch, factr = ftol / eps
        self.x = np.array(x0, dtype=float)
        self.S, self.Y, self.gamma = [], [], 1.0
        self.iter = self.nit = self.nfev = 0
        self.term, self.phase, self.req = None, "start", self.x.copy()

    def twoloop(self, g):
        q, al = g.copy(), []
        for si, yi in zip(reversed(self.S), reversed(self.Y)):
            rho = 1.0 / np.dot(yi, si)
            a = rho * np.dot(si, q)
            q = q - a * yi
            al.append((rho, a))
        al.reverse()
        r = self.gamma * q
        for (rho, a), si, yi in zip(al, self.S, self.Y):
            r = r + si * (a - rho * np.dot(yi, r))
        return r

    def begin(self):
        self.xb, self.fb, self.gb = self.x.copy(), self.f, self.g.copy()
        self.d = -self.twoloop(self.g) if self.S else -self.g
        self.gdold = float(np.dot(self.g, self.d))
        if not self.gdold < 0:
            return self.abort()
        stp0 = min(1.0 / np.linalg.norm(self.d), 1e10) if self.iter == 0 else 1.0
        self.ls = DCSRCH(None, None, 1e-3, 0.9, 0.1, 0.0, 1e10)
        self.stp, _, _, self.task = self.ls._iterate(stp0, self.f, self.gdold, b"START")
        self.ifun = 0
        return self.request()

    def request(self):
        self.ifun += 1
        if self.ifun - 1 >= self.maxls:
            return self.abort()
        self.req, self.phase = self.xb + self.stp * self.d, "ls"
        return self.req

    def abort(self):
        self.x, self.f, self.g = self.xb.copy(), self.fb, self.gb.copy()
        if not self.S:
            self.term, self.phase = "line_search_failed", "done"
            return None
        self.S, self.Y, self.gamma = [], [], 1.0
        return self.begin()

    def tell(self, f, g):
        self.nfev += 1
        g = np.array(g, dtype=float)
        if self.phase == "start":
            self.f, self.g = f, g
            if np.max(np.abs(g)) <= self.gtol:
                self.term, self.phase = "grad_tol", "done"
                return None
            return self.begin()
        gd = float(np.dot(g, self.d))
        stp, _, _, self.task = self.ls._iterate(self.stp, f, gd, self.task)
        if self.task[:2] == b"FG":
            self.stp = stp
            return self.request()
        alpha = self.stp  # CONVERGENCE and WARNING both accept the last trial
        self.x, self.fold, self.f, self.gold, self.g = self.xb + alpha * self.d, self.fb, f, self.gb, g
        self.iter += 1
        self.nit += 1
        if self.nit >= self.maxiter:
            self.term = "max_iter"
        elif self.nfev > self.maxfun:
            self.term = "max_eval"
        elif np.max(np.abs(g)) <= self.gtol:
            self.term = "grad_tol"
        elif self.fold - f <= self.tol * max(abs(self.fold), abs(f), 1.0):
            self.term = "f_tol"
        if self.term:
            self.phase = "done"
            return None
        y = g - self.gold
        dr = gd - self.gdold if alpha == 1.0 else (gd - self.gdold) * alpha
        ddum = -self.gdold if alpha == 1.0 else -self.gdold * alpha
        if not dr <= EPS * ddum:
            self.S.append(alpha * self.d)
            self.Y.append(y)
            if len(self.S) > self.m:
                self.S.pop(0)
                self.Y.pop(0)
            self.gamma = dr / float(np.dot(y, y))
        return self.begin()


def mirror_replay(row, evals):
    """Replay SciPy's (f, g) through the mirror; returns (counts and termination agree, worst
    ratio of (|x_mirror - x_scipy| - x_slack) / (eps x_scale) over all requests)."""
    M = Mirror(row["x0"], row["maxcor"], row["gtol"], row["ftol"], row["maxiter"], row["maxfun"], row["maxls"])
    x, worst, i = M.req, 0.0, 0
    while True:
        if i >= len(evals):
            return False, worst
        e = evals[i]
        over = np.maximum(np.abs(x - e["x"]) - e["x_slack"], 0.0)
        worst = max(worst, float(np.max(over / np.maximum(EPS * e["x_scale"], 1e-300))))
        x = M.tell(e["f"], e["g"])
        i += 1
        if x is None:
            break
    ok = i == len(evals) and M.term == row["termination"] and M.nit == row["nit"] and M.nfev == row["nfev"]
    return ok, worst

