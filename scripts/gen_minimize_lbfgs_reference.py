REL_TOL = 1e-8
ABS_TOL = 1e-12
# Exact (string equality): ids, outcomes, counts, flags, the exact call text. Floats: within
# REL_TOL relative or ABS_TOL absolute. The libm-free closed forms and SciPy's C code agree across
# platforms to the last bits, except where BLAS (the quadratics' matrix-vector products and the
# dot products inside L-BFGS-B) sums in a different order; the path (counts, termination) is
# pinned exactly, the values loosely.
FLOAT_COLS = {
    "runs.csv": {"ftol", "gtol", "f", "ginf", "x0", "x", "dir_ratio", "mirror_ratio"},
    "evals.csv": {"x", "f", "g", "x_scale", "x_slack"},
    "searches.csv": {"gamma_scipy", "gamma_exact", "stp0", "x_base", "g_base", "d", "d_exact", "d_scale"},
    "pairs.csv": {"s", "y"},
}


def parse_csv(text):
    lines = [l for l in text.splitlines() if l and not l.startswith("#")]
    header = lines[0].split(",")
    return header, [dict(zip(header, l.split(","))) for l in lines[1:]]


def floats_agree(a, b):
    if a == b:
        return True
    try:
        xs = [float(t) for t in a.split(";")]
        ys = [float(t) for t in b.split(";")]
    except ValueError:
        return False
    if len(xs) != len(ys):
        return False
    for x, y in zip(xs, ys):
        if math.isnan(x) or math.isnan(y):
            if not (math.isnan(x) and math.isnan(y)):
                return False
        elif x != y and abs(x - y) > max(REL_TOL * max(abs(x), abs(y)), ABS_TOL):
            return False
    return True


def check(new, data):
    problems = []
    for name, text in new.items():
        path = data / name
        if not path.exists():
            problems.append(f"{name}: missing")
            continue
        h1, r1 = parse_csv(path.read_text())
        h2, r2 = parse_csv(text)
        if h1 != h2 or len(r1) != len(r2):
            problems.append(f"{name}: header or row count differs ({len(r1)} committed, {len(r2)} regenerated)")
            continue
        fcols = FLOAT_COLS.get(name, set())
        for i, (a, b) in enumerate(zip(r1, r2)):
            for c in h1:
                ok = floats_agree(a[c], b[c]) if c in fcols else a[c] == b[c]
                if not ok:
                    problems.append(f"{name} row {i} column {c}: committed {a[c][:60]!r}, regenerated {b[c][:60]!r}")
    for p in problems[:40]:
        print("MISMATCH", p)
    print("check:", "FAILED" if problems else "ok", f"({len(problems)} problems)")
    return 1 if problems else 0


def coverage():
    """Every termination, the restart and the counting quirks must be in the data (the Rust tests
    name these runs)."""
    by = {r["id"]: r for r in RUNS}
    terms = {r["termination"] for r in RUNS}
    assert terms >= {"grad_tol", "f_tol", "max_iter", "max_eval", "line_search_failed"}, terms
    assert by["stationary_start"]["nfev"] == 1 and by["stationary_start"]["nit"] == 0
    for ls in (1, 2, 3):
        assert by[f"maxls{ls}_rosen2_first"]["maxls"] == ls
    assert by["maxls1_rosen2_first"]["termination"] == "line_search_failed"
    assert by["maxls1_rosen2_first"]["nfev"] == 1 + 1, "first search fails after maxls evaluations"
    assert by["maxfun1_rosen2"]["nfev"] == 3, "maxfun is checked only after an accepted iteration"
    assert any(r["nrestart"] > 0 and r["termination"] == "line_search_failed" for r in RUNS)
    assert any(r["nrestart"] > 0 and r["termination"] == "grad_tol" for r in RUNS)
    assert by["maxiter_eq_k_rosen5"]["termination"] == "max_iter"
    assert by["maxiter_eq_k_ftol_rosen5"]["termination"] == "max_iter"
    for rid in ("maxiter_eq_k1_rosen5", "maxiter_eq_k1_quad5_k1e2"):
        assert by[rid]["termination"] == "grad_tol"


