def options_text(opts):
    return "{" + ", ".join(f"'{k}': {v!r}" for k, v in opts.items()) + "}"


class OutOfRegime(Exception):
    """A run whose direction error or mirror replay exceeds the stated bounds (README.md)."""


def snapshot():
    return len(RUNS), len(EVALS), len(SEARCHES), len(PAIRS), len(DIVERGENCES)


def rollback(snap):
    del RUNS[snap[0]:], EVALS[snap[1]:], SEARCHES[snap[2]:], PAIRS[snap[3]:], DIVERGENCES[snap[4]:]


def run(rid, group, problem, note="", x0=None, **overrides):
    snap = snapshot()
    try:
        return run_(rid, group, problem, note, x0, snap, **overrides)
    except OutOfRegime:
        rollback(snap)
        raise


def run_(rid, group, problem, note, x0, snap, **overrides):
    opts = dict(DEFAULTS)
    opts.update(overrides)
    pfun, px0 = PROBLEMS[problem]
    x0 = px0 if x0 is None else np.asarray(x0, dtype=float)

    # the public entry point; its objective wrapper logs every call
    calls: list[np.ndarray] = []

    def logged(x):
        calls.append(np.array(x, dtype=float))
        return pfun(x)

    official = so.minimize(logged, x0, jac=True, method="L-BFGS-B", bounds=None, options=dict(opts))
    rep = replica(pfun, x0, **opts)

    # the replica must be the same algorithm run, not a look-alike
    assert official.nit == rep["nit"] and official.nfev == rep["nfev"], rid
    assert np.array_equal(official.x, rep["x"]) and official.fun == rep["f"], rid
    task = rep["task"]
    msg_status = (
        0 if task[0] == 4 else 1 if (rep["nfev"] > opts["maxfun"] or rep["nit"] >= opts["maxiter"]) else 2
    )
    assert official.status == msg_status, (rid, official.status, msg_status, official.message)
    assert len(calls) == official.nfev, (rid, len(calls), official.nfev)
    for a, b in zip(calls, [q["x"] for q in rep["reqs"]]):
        assert np.array_equal(a, b), rid
    nreq = len(rep["reqs"])
    if nreq != rep["nfev"]:
        DIVERGENCES.append((rid, "requests_vs_nfev", str(nreq), str(rep["nfev"]),
                            "ScalarFunction cached a repeated x"))  # fmt: skip

    termination = TERMINATION.get(task, "line_search_failed" if task[0] == 8 else "error")
    assert termination != "error", (rid, task)
    n = len(x0)
    reqs = rep["reqs"]

    # pairs, searches, evals
    pair_ids: dict[tuple[int, int], int] = {}
    local_pairs: list[dict] = []
    epoch = 0
    cum = np.zeros(n)  # sum over accepted searches of the per-step rounding scale
    cum_slack = np.zeros(n)  # sum over accepted searches of |stp| |d_scipy - d_exact|
    search = -1
    nrestart = 0
    prev_col = 0
    last_search_row = None
    for k, q in enumerate(reqs):
        if q["msg"] == 301:  # the start evaluation
            EVALS.append(dict(run=rid, k=k, search=-1, ifun=0, x=q["x"], f=q["f"], g=q["g"],
                              accepted=0, x_scale=np.abs(q["x"]), x_slack=np.zeros(n)))  # fmt: skip
            continue
        if q["first"]:
            search += 1
            if q["iupdat"] == 0:
                epoch += 1
            if q["iter"] > 0 and q["col"] == 0 and prev_col > 0:
                nrestart += 1
            prev_col = q["col"]
            m = rep["m"]
            col, head, iupdat = q["col"], q["head"], q["iupdat"]
            ids = []
            S, Y = [], []
            for i in range(col):
                slot = (head + i) % m
                key = (epoch, iupdat - col + 1 + i)
                s_i, y_i = q["ws"][slot], q["wy"][slot]
                if key in pair_ids:
                    p = pair_ids[key]
                    assert np.array_equal(local_pairs[p]["s"], s_i) and np.array_equal(local_pairs[p]["y"], y_i), (rid, key)
                else:
                    p = len(local_pairs)
                    pair_ids[key] = p
                    local_pairs.append(dict(run=rid, p=p, s=s_i, y=y_i))
                ids.append(pair_ids[key])
                S.append(s_i)
                Y.append(y_i)
            d_exact, d_scale, gamma_exact = exact_direction(S, Y, q["gb"])
            # sanity: the first trial is t + stp d (or z = t + d for stp == 1)
            trial = q["t"] + q["stp"] * q["d"]
            assert np.all(np.abs(trial - q["x"]) <= 4 * EPS * (np.abs(q["t"]) + np.abs(q["stp"] * q["d"]))), (rid, k)
            last_search_row = dict(
                run=rid, j=search, k0=k, iter=q["iter"], col=col, iupdat=iupdat, nskip=q["nskip"],
                gamma_scipy=1.0 / q["theta"], gamma_exact=gamma_exact, stp0=q["stp"],
                x_base=q["t"], g_base=q["gb"], d=q["d"], d_exact=d_exact, d_scale=d_scale,
                pair_lo=ids[0] if ids else "none", pair_hi=ids[-1] if ids else "none",
                restart=int(q["iter"] > 0 and col == 0),
            )  # fmt: skip
            SEARCHES.append(last_search_row)
            d_scale_vec = np.array(d_scale)
            d_err = np.abs(q["d"] - np.array(d_exact))
        xs = cum + np.abs(last_search_row["x_base"]) + abs(q["stp"]) * d_scale_vec
        EVALS.append(dict(run=rid, k=k, search=search, ifun=q["ifun"], x=q["x"], f=q["f"], g=q["g"],
                          accepted=int(q["accepted"]), x_scale=xs,
                          x_slack=cum_slack + abs(q["stp"]) * d_err))  # fmt: skip
        if q["accepted"]:
            cum = cum + abs(q["stp"]) * d_scale_vec + np.abs(q["x"])
            cum_slack = cum_slack + abs(q["stp"]) * d_err
    PAIRS.extend(local_pairs)
    # direction accuracy of SciPy itself, and the float64 mirror's replay against the data
    run_evals = EVALS[snap[1]:]
    dir_ratio = 0.0
    for srow in SEARCHES[snap[2]:]:
        sc = np.array(srow["d_scale"])
        err = np.abs(np.array(srow["d"]) - np.array(srow["d_exact"]))
        dir_ratio = max(dir_ratio, float(np.max(np.where(sc > 0, err / np.maximum(EPS * sc, 1e-300), 0.0))))
    if dir_ratio > C_DIR / 2:
        raise OutOfRegime(f"{rid}: SciPy direction {dir_ratio:.1f} eps scale > {C_DIR // 2} (half of {C_DIR})")
    mrow = dict(x0=x0, maxcor=opts["maxcor"], gtol=opts["gtol"], ftol=opts["ftol"], maxiter=opts["maxiter"],
                maxfun=opts["maxfun"], maxls=opts["maxls"], termination=termination, nit=official.nit,
                nfev=official.nfev)  # fmt: skip
    ok, mirror_ratio = mirror_replay(mrow, run_evals)
    if not ok:
        raise SystemExit(f"{rid}: the mirror disagrees with SciPy on counts or termination (algorithm error)")
    if mirror_ratio > C_X / 2:
        raise OutOfRegime(f"{rid}: mirror replay {mirror_ratio:.1f} eps scale > {C_X // 2} (half of {C_X})")
    RUNS.append(dict(
        id=rid, group=group, problem=problem, n=n, x0=x0, maxcor=opts["maxcor"], ftol=opts["ftol"],
        gtol=opts["gtol"], maxfun=opts["maxfun"], maxiter=opts["maxiter"], maxls=opts["maxls"],
        call=("minimize(fun, x0, jac=True, method='L-BFGS-B', bounds=None, options="
              + options_text(opts) + ")"),
        status=official.status, message=official.message.replace(",", ";").replace(" ", "_"),
        termination=termination, nit=official.nit, nfev=official.nfev, njev=official.njev,
        nrequests=nreq, nskip=rep["nskip"], nrestart=nrestart, nsearch=search + 1,
        f=official.fun, ginf=float(np.max(np.abs(official.jac))), x=official.x,
        dir_ratio=round(dir_ratio, 2), mirror_ratio=round(mirror_ratio, 2), note=note,
    ))  # fmt: skip
    return RUNS[-1]


