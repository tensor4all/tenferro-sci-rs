def rosen(x):
    return float(so.rosen(x)), np.array(so.rosen_der(x), dtype=float)


def beale(x):
    a, b = x
    t1 = 1.5 - a + a * b
    t2 = 2.25 - a + a * b * b
    t3 = 2.625 - a + a * b**3
    f = t1 * t1 + t2 * t2 + t3 * t3
    ga = 2 * t1 * (b - 1) + 2 * t2 * (b * b - 1) + 2 * t3 * (b**3 - 1)
    gb = 2 * t1 * a + 2 * t2 * 2 * a * b + 2 * t3 * 3 * a * b * b
    return float(f), np.array([ga, gb])


def himmelblau(x):
    a, b = x
    u = a * a + b - 11
    v = a + b * b - 7
    return float(u * u + v * v), np.array([4 * a * u + 2 * v, 2 * u + 4 * b * v])


def powell(x):  # Powell's singular function, as in Moré, Garbow & Hillstrom, ACM TOMS 7(1), 17-41, 1981
    a, b, c, d = x
    f1, f2, f3, f4 = a + 10 * b, math.sqrt(5.0) * (c - d), (b - 2 * c) ** 2, math.sqrt(10.0) * (a - d) ** 2
    f = f1 * f1 + f2 * f2 + f3 * f3 + f4 * f4
    g = np.array([
        2 * f1 + 2 * f4 * math.sqrt(10.0) * 2 * (a - d),
        20 * f1 + 2 * f3 * 2 * (b - 2 * c),
        2 * f2 * math.sqrt(5.0) - 2 * f3 * 4 * (b - 2 * c),
        -2 * f2 * math.sqrt(5.0) - 2 * f4 * math.sqrt(10.0) * 2 * (a - d),
    ])
    return float(f), g


def householder_quadratic(n, cond):
    """f(x) = 1/2 (x - xs)^T A (x - xs), A = P diag(lam) P, P = I - 2 u u^T, u = v/|v|,
    v = (1, ..., n), lam_i = cond^(i/(n-1)); xs = (1, ..., n). A is applied without forming it:
    A y = lam*y - 2 u (lam*u . y) - 2 (lam*u)(u . y) + 4 (u . lam*u) u (u . y)."""
    v = np.arange(1, n + 1, dtype=float)
    u = v / math.sqrt(float(v @ v))
    lam = cond ** (np.arange(n) / max(n - 1, 1))
    lu = lam * u
    c = float(u @ lu)
    xs = np.arange(1, n + 1, dtype=float)

    def apply(y):
        uy = float(u @ y)
        return lam * y - 2 * u * float(lu @ y) - 2 * lu * uy + 4 * c * u * uy

    def fun(x):
        d = x - xs
        g = apply(d)
        return 0.5 * float(d @ g), g

    return fun


