def free_nit(problem, **kw):
    snap = snapshot()
    try:
        r = run("probe", "probe", problem, **kw)
    except OutOfRegime:
        return None
    rollback(snap)
    return r


def capped(rid, group, problem, caps, **kw):
    """The run with the first `maxiter` cap (None = default) that stays inside the stated bounds: past
    some iteration rounding differences between independent implementations are amplified by the
    problem (README.md), and the replay claim stops there."""
    for cap in caps:
        try:
            extra = {} if cap is None else dict(maxiter=cap)
            return run(rid, group, problem, **kw, **extra)
        except OutOfRegime as e:
            print("  out of regime:", e)
    raise SystemExit(f"{rid}: no cap in {caps} stays inside the bounds")


def cases():
    # defaults on every problem: GradTol or FTol after k iterations
    for p in PROBLEMS:
        run(f"default_{p}", "default", p)
    # ftol = 0 forces the gradient test to decide where the default would stop on FTol
    for p in ("rosen2", "rosen5", "beale", "himmelblau"):
        run(f"ftol0_{p}", "ftol0", p, ftol=0.0, note="ftol = 0: only gtol, maxiter, maxfun, line search can stop")
    # memory sizes: m = 1 (every iteration drops a pair), 3, and unlimited-in-practice
    caps = [None, 60, 50, 40, 35, 30, 25, 20, 15, 12, 10, 8, 6]
    for m in (1, 3):
        for p in ("rosen5", "quad10_k1e2", "powell4"):
            capped(f"m{m}_{p}", "memory", p, caps, maxcor=m)
    run("m50_quad10_k1e2", "memory", "quad10_k1e2", maxcor=50)
    # quadratics, tight gtol: the stopping point is determined by gtol alone
    for p in ("quad5_k1", "quad5_k1e2", "quad5_k1e4", "quad10_k1e2"):
        for gt in (1e-9, 1e-8, 1e-7, 1e-6, 3e-6, 1e-5):
            try:
                run(f"tight_{p}", "tight", p, gtol=gt, ftol=0.0)
                break
            except OutOfRegime as e:
                print("  out of regime:", e)
        else:
            print(f"  tight_{p}: no gtol stays inside the bounds; not recorded")
    # --- terminations -----------------------------------------------------------------------
    run("stationary_start", "termination", "quad5_k1e2", x0=np.arange(1.0, 6.0),
        note="x0 is the minimizer: GradTol at the start, one evaluation, zero iterations")  # fmt: skip
    run("maxiter1_rosen2", "termination", "rosen2", maxiter=1, note="MaxIter after the first iteration")
    # maxiter before the gradient test: free run to find k, then maxiter = k and k + 1
    for p in ("quad5_k1e2", "rosen5"):
        kw = dict(ftol=0.0, gtol=1e-5)
        free = free_nit(p, **kw)
        assert free["termination"] == "grad_tol", (p, free["termination"])
        k = free["nit"]
        r = run(f"maxiter_eq_k_{p}", "maxiter_order", p, maxiter=k, **kw,
                note=f"the free run ends with GradTol at nit = {k}; maxiter = {k} reports MaxIter at the same iterate")  # fmt: skip
        assert r["termination"] == "max_iter" and r["nit"] == k
        r = run(f"maxiter_eq_k1_{p}", "maxiter_order", p, maxiter=k + 1, **kw,
                note=f"maxiter = {k} + 1: GradTol as the free run")  # fmt: skip
        assert r["termination"] == "grad_tol" and r["nit"] == k
    # the same with FTol: the free Rosenbrock-5 run ends with FTol at nit = 49 (probe of the review)
    free = free_nit("rosen5")
    assert free["termination"] == "f_tol", free["termination"]
    run("maxiter_eq_k_ftol_rosen5", "maxiter_order", "rosen5", maxiter=free["nit"],
        note="FTol would end the free run at this iteration; maxiter reports MaxIter")  # fmt: skip
    # maxfun: checked only after an accepted iteration, strict '>'
    for mf in (5, 10, 20):
        run(f"maxfun{mf}_rosen5", "maxfun", "rosen5", maxfun=mf)
    run("maxfun1_rosen2", "maxfun", "rosen2", maxfun=1, note="nfev = 2 > 1 after the first accepted step")
    # maxls: first search fails with col = 0 (nfev = 1 + maxls)
    for ls in (1, 2, 3):
        run(f"maxls{ls}_rosen2_first", "maxls", "rosen2", maxls=ls)
    # FTol with a large ftol on a quadratic
    run("ftol_large_quad5_k1e2", "termination", "quad5_k1e2", ftol=1e-2, note="large ftol: FTol after few iterations")
    search_cases()


def search_cases():
    """Deterministic searches for runs with a restart (col drops to 0 at iter > 0) and with a
    skipped update. The first candidate that shows the feature is recorded."""
    found = {}
    for ls in (2, 3, 4, 5, 6, 8):
        for p in ("rosen2", "rosen2_far", "rosen5", "beale", "himmelblau", "powell4"):
            r = free_nit(p, maxls=ls)
            key = None
            if r["nrestart"] > 0:
                key = "restart_" + r["termination"]
            if r["nskip"] > 0:
                key = "skip_" + r["termination"]
            if key and key not in found:
                found[key] = (p, ls)
    for key, (p, ls) in sorted(found.items()):
        run(f"search_{key}", "search", p, maxls=ls, note=f"first candidate with {key.split('_')[0]} (maxls = {ls})")
    print("  search found:", sorted(found))
    REQUIRED_SEARCH.update(found)


