"""Generate the SciPy reference data for `minimize::lbfgs` (the unconstrained path of L-BFGS-B).

Run from the repository root:

    uv run scripts/gen_minimize_lbfgs_reference.py            # regenerate the CSVs
    uv run scripts/gen_minimize_lbfgs_reference.py --check    # CI: compare, write nothing

Source mirrored (provenance): SciPy v1.16.3, commit b9105ccc2237f57acb1060202cd77f6dd264fb34,
``scipy/optimize/_lbfgsb_py.py`` (``_minimize_lbfgsb``, the driver loop) and
``scipy/optimize/__lbfgsb.c`` (``setulb``/``mainlb``/``lnsrlb``). SciPy is BSD-3-Clause.

What is recorded, and how
-------------------------
Every run is executed twice with SciPy 1.16.3:

* through the public entry point
  ``scipy.optimize.minimize(fun, x0, jac=True, method="L-BFGS-B", bounds=None, options=...)``
  with **all** options passed explicitly (the exact call is the ``call`` column of runs.csv);
* through a replica of ``_minimize_lbfgsb``'s own loop that calls ``_lbfgsb.setulb`` directly, so
  that SciPy's internal state can be read at every request: ``isave`` (``col``, ``head``,
  ``iter``, ``iupdat``, ``nskip``, ``ifun``), ``dsave`` (``theta``, ``stp``) and the workspace
  ``wa`` (the stored pairs ``S``, ``Y``, the search direction ``d``, the saved point ``t`` and
  gradient ``r``). The workspace layout is the one ``setulb`` computes (``__lbfgsb.c``, ~line 300);
  the indices of ``isave`` that ``mainlb`` sees are shifted by 21 in the array ``setulb`` receives.

The replica must agree with the public call on the whole evaluation sequence, the final point,
``nit``, ``nfev``, ``status`` and ``message``; the generator asserts it for every run.

Outputs (committed; regenerating them is a separate commit), all in
crates/minimize/tests/data/lbfgs/:

* runs.csv      -- one row per run: problem, options, the exact SciPy call, SciPy's status, message,
                   counts, final point, and the Rust ``Termination`` the message maps to
* evals.csv     -- every evaluation SciPy requested, in order: x, f, g, the search it belongs to,
                   whether it was accepted, and ``x_scale`` (the rounding scale of x, README.md)
* searches.csv  -- one row per line search: SciPy's direction ``d`` and the exact direction
                   ``-H g`` recomputed in mpmath (60 digits) from the stored pairs, with the
                   rounding scale ``d_scale``
* pairs.csv     -- the (s, y) pairs exactly as SciPy stored them in ``S`` and ``Y``
* divergences.csv -- runs where the replica's request count differs from SciPy's ``nfev``
                   (SciPy's ``ScalarFunction`` caches the last x)

Floats are written with ``repr(float(x))`` (shortest round-trip); vectors are ``;``-separated.
"""

