# Offsets into `wa` (setulb, __lbfgsb.c ~line 300): ws, wy, wsy, wss, wt, wn(4 m^2), wsnd(4 m^2), z, r, d, t, xp, wa(8 m)
def wa_layout(n, m):
    ws = 0
    wy = m * n
    z = 2 * m * n + 11 * m * m
    return dict(ws=ws, wy=wy, z=z, r=z + n, d=z + 2 * n, t=z + 3 * n)


def fmt(x) -> str:
    return repr(float(x))


def vec(v) -> str:
    return ";".join(fmt(t) for t in v)


def replica(fun, x0, maxcor, ftol, gtol, maxfun, maxiter, maxls):
    """`_minimize_lbfgsb`'s loop (bounds=None), reading SciPy's state at every request."""
    m = maxcor
    factr = ftol / np.finfo(float).eps
    x0 = np.asarray(x0, dtype=float).ravel()
    n = x0.shape[0]
    mj = MemoizeJac(fun)
    sf = _prepare_scalar_function(mj, x0, jac=mj.derivative, args=(), epsilon=1e-8, bounds=None,
                                  finite_diff_rel_step=None, workers=None)  # fmt: skip
    fg = sf.fun_and_grad
    nbd = np.zeros(n, np.int32)
    lo = np.zeros(n)
    up = np.zeros(n)
    x = np.array(x0, dtype=np.float64)
    f = np.array(0.0)
    g = np.zeros(n)
    wa = np.zeros(2 * m * n + 5 * n + 11 * m * m + 8 * m)
    iwa = np.zeros(3 * n, dtype=np.int32)
    task = np.zeros(2, dtype=np.int32)
    ln_task = np.zeros(2, dtype=np.int32)
    lsave = np.zeros(4, dtype=np.int32)
    isave = np.zeros(44, dtype=np.int32)
    dsave = np.zeros(29)
    L = wa_layout(n, m)
    n_it = 0
    reqs = []
    while True:
        g = g.astype(np.float64)
        _lbfgsb.setulb(m, x, lo, up, nbd, f, g, factr, gtol, wa, iwa, task, lsave, isave, dsave, maxls, ln_task)
        if task[0] == 3:
            first = int(task[1]) == 302 and int(isave[35]) == 1  # first trial of a line search
            req = dict(
                x=x.copy(), msg=int(task[1]), first=first, accepted=False,
                iter=int(isave[29]), col=int(isave[27]), head=int(isave[26]),
                iupdat=int(isave[30]), nskip=int(isave[25]), ifun=int(isave[35]),
                theta=float(dsave[0]), stp=float(dsave[13]),
            )  # fmt: skip
            if first:
                req["d"] = wa[L["d"] : L["d"] + n].copy()
                req["t"] = wa[L["t"] : L["t"] + n].copy()
                req["gb"] = wa[L["r"] : L["r"] + n].copy()
                req["ws"] = wa[L["ws"] : L["ws"] + m * n].reshape(m, n).copy()
                req["wy"] = wa[L["wy"] : L["wy"] + m * n].reshape(m, n).copy()
            f, g = fg(x)
            req.update(f=float(f), g=np.array(g, dtype=float).copy())
            reqs.append(req)
        elif task[0] == 1:
            n_it += 1
            reqs[-1]["accepted"] = True
            if n_it >= maxiter:
                task[0], task[1] = 5, 504
            elif sf.nfev > maxfun:
                task[0], task[1] = 5, 502
        else:
            break
    return dict(
        x=x.copy(), f=float(f), g=np.array(g, dtype=float), nit=n_it, nfev=sf.nfev, njev=sf.ngev,
        task=(int(task[0]), int(task[1])), reqs=reqs, nskip=int(isave[25]), m=m, n=n,
    )  # fmt: skip


