"""Generate the SciPy reference data for `minimize::linesearch` (Moré-Thuente / DCSRCH).

Run from the repository root:

    uv run scripts/gen_minimize_linesearch_reference.py            # regenerate the CSVs
    uv run scripts/gen_minimize_linesearch_reference.py --check    # CI: compare, write nothing

``--check`` regenerates everything in memory and compares it with the committed CSVs (or with
``--data DIR``); it writes nothing and exits non-zero with a readable diff on a mismatch. It does
not compare bytes: run ids, outcomes, tasks, counts, None-ness and the number of trials per run
must be identical, every float must agree within 1e-12 relative (or be exactly equal, including
both zero, both inf, both nan), except phi' (trials.csv `dphi`), which is bounded by the
dot-product error bound 4 n eps dphi_scale (Higham, section 3.1) with the committed scale: phi'
of a run that converges at its first trial is cancellation noise of a BLAS dot product. The
contract is in crates/minimize/tests/data/linesearch/README.md. The closed-form runs use libm ``exp``/``sin``/``cos``/``pow``,
which Linux glibc and macOS libm may round one ulp apart, and that ulp is invisible to the
Rust tests' tolerance but not to a byte compare. The ``#`` header lines (date, versions) are
ignored.

Outputs (committed; regenerating them is a separate commit), all in
crates/minimize/tests/data/linesearch/:

* cases.csv       -- one row per run: inputs, options, SciPy's final task and step, counts
* trials.csv      -- every trial (alpha, phi, phi') SciPy evaluated, in order
* divergences.csv -- cases where SciPy's own run and the closed-form run differ

Two kinds of run are recorded, both through SciPy 1.16.3:

* run = ``scipy``:  SciPy's own test functions (numpy, 20-d dot products), imported from the
  wheel (``scipy.optimize.tests.test_linesearch.TestLineSearch``). The Rust *replay* test feeds
  these recorded values back into the ask/tell state machine.
* run = ``closed``: the same problems as closed-form scalar functions in plain Python floats
  (libm exp/sin/cos/pow), with the same operation order as the Rust test functions, so that the
  Rust *live* test evaluates exactly the same arithmetic. The line functions become the quadratic
  phi(a) = A*a*a + B*a + C (coefficients recorded as p0, p1, p2). Where this changes SciPy's
  evaluation count, step or outcome the difference is written to divergences.csv.

The hook sits at ``DCSRCH.__call__`` (it sees the resolved inputs and the final task) and wraps
``phi``/``derphi`` only for the duration of that call, so SciPy's test-side evaluations never
reach the log. ``scalar_search_wolfe1`` hard-codes maxiter = 100; the maxiter = 2 case and the
paper tables therefore call ``DCSRCH`` directly (kind = dcsrch), the rest through
``scalar_search_wolfe1`` / ``line_search_wolfe1`` (kind = wolfe1).

Floats are written with ``repr(float(x))`` (shortest round-trip), which Rust ``parse::<f64>``
reads back exactly; ``inf``/``-inf``/``nan`` and ``none`` are spelled out.
"""

