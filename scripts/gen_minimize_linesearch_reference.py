    dcsrch("below_stpmin", "edge", "shiftq", (5.0,), 1e-4, 0.9, 1e-9, stpmin=1e-8, stpmax=50.0,
           note="alpha0 < stpmin")  # fmt: skip

    # --- reasons found by a small deterministic search; first candidate reaching the target wins
