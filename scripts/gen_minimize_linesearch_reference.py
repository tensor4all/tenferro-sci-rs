REASONS = {
    "CONVERGENCE": "converged",
    "WARNING: ROUNDING ERRORS PREVENT PROGRESS": "rounding",
    "WARNING: XTOL TEST SATISFIED": "xtol",
    "WARNING: STP = STPMAX": "stpmax",
    "WARNING: STP = STPMIN": "stpmin",
    "WARN": "nonfinite_step",
    "WARNING: dcsrch did not converge within max iterations": "maxiter",
    "ERROR: STP .LT. STPMIN": "err_below_stpmin",
    "ERROR: STP .GT. STPMAX": "err_above_stpmax",
    "ERROR: INITIAL G .GE. ZERO": "err_not_descent",
}


def fmt(x) -> str:
    if x is None:
        return "none"
    return repr(float(x))


_orig_call = DCSRCH.__call__
LAST: dict = {}


def _hooked(self, alpha1, phi0=None, derphi0=None, maxiter=100):
    p, d = self.phi, self.derphi
    log: list[tuple[str, float, float]] = []

    def pw(a):
        v = p(a)
        log.append(("p", float(a), float(v)))
        return v

    def dw(a):
        v = d(a)
        log.append(("d", float(a), float(v)))
        return v

    self.phi, self.derphi = pw, dw
    try:
        stp, phi1, phi0r, task = _orig_call(self, alpha1, phi0=phi0, derphi0=derphi0, maxiter=maxiter)
    finally:
        self.phi, self.derphi = p, d
    ps = [e for e in log if e[0] == "p"]
    ds = [e for e in log if e[0] == "d"]
    phi0_given = phi0 is not None
    dphi0_given = derphi0 is not None
    if not phi0_given:
        assert ps[0][1] == 0.0
        ps = ps[1:]
    if not dphi0_given:
        assert ds[0][1] == 0.0
        dphi0_val = ds[0][2]
        ds = ds[1:]
    else:
        dphi0_val = float(derphi0)
    assert len(ps) == len(ds) and all(a[1] == b[1] for a, b in zip(ps, ds))
    LAST.clear()
    LAST.update(
        alpha1=float(alpha1), phi0=float(phi0r), dphi0=dphi0_val,
        phi0_given=phi0_given, dphi0_given=dphi0_given, maxiter=maxiter,
        ftol=self.ftol, gtol=self.gtol, xtol=self.xtol, stpmin=self.stpmin, stpmax=self.stpmax,
        stp=None if stp is None else float(stp), phi1=float(phi1), task=task.decode(),
        trials=[(a[1], a[2], b[2]) for a, b in zip(ps, ds)],
        n_zero_phi=0 if phi0_given else 1, n_zero_dphi=0 if dphi0_given else 1,
    )  # fmt: skip
    return stp, phi1, phi0r, task


DCSRCH.__call__ = _hooked

CASES: list[dict] = []
TRIALS: list[tuple[str, int, float, float, float]] = []


def record(cid, run, kind, group, fn, params, old_phi0, note=""):
    L = LAST
    reason = REASONS[L["task"]]
    row = dict(
        id=cid, run=run, kind=kind, group=group, fn=fn,
        p0=fmt(params[0]) if len(params) > 0 else "none",
        p1=fmt(params[1]) if len(params) > 1 else "none",
        p2=fmt(params[2]) if len(params) > 2 else "none",
        phi0=fmt(L["phi0"]), old_phi0=fmt(old_phi0), dphi0=fmt(L["dphi0"]),
        phi0_given=int(L["phi0_given"]), dphi0_given=int(L["dphi0_given"]),
        alpha1=fmt(L["alpha1"]), ftol=fmt(L["ftol"]), gtol=fmt(L["gtol"]), xtol=fmt(L["xtol"]),
        stpmin=fmt(L["stpmin"]), stpmax=fmt(L["stpmax"]), maxiter=L["maxiter"],
        reason=reason, task=L["task"].replace(",", ";"), stp=fmt(L["stp"]), phi1=fmt(L["phi1"]),
        phi_evals=len(L["trials"]) + L["n_zero_phi"], dphi_evals=len(L["trials"]) + L["n_zero_dphi"],
        n_trials=len(L["trials"]), note=note,
    )  # fmt: skip
    CASES.append(row)
    for k, (a, f, g) in enumerate(L["trials"]):
        TRIALS.append((cid, k, a, f, g))
    return row


def wolfe1(cid, run, group, fn, params, phi, dphi, phi0, old_phi0, dphi0, *, c1=1e-4, c2=0.9,
           amax=50.0, amin=1e-8, xtol=1e-14, note=""):  # fmt: skip
    ls.scalar_search_wolfe1(phi, dphi, phi0, old_phi0, dphi0, c1=c1, c2=c2, amax=amax, amin=amin, xtol=xtol)
    return record(cid, run, "wolfe1", group, fn, params, old_phi0, note)


def dcsrch(cid, group, fn, params, ftol, gtol, alpha0, *, xtol=1e-14, stpmin=0.0, stpmax=1e10,
           maxiter=100, phi0=None, dphi0=None, note="", run="closed"):  # fmt: skip
    phi, dphi = closed(fn, params)
    if phi0 is None:
        phi0, dphi0 = FUNCS[fn](0.0, params)
    DCSRCH(phi, dphi, ftol, gtol, xtol, stpmin, stpmax)(alpha0, phi0=phi0, derphi0=dphi0, maxiter=maxiter)
    return record(cid, run, "dcsrch", group, fn, params, None, note)


