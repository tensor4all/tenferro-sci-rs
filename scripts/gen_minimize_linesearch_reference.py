def sf1(a, p):
    return (-a - a**3 + a**4, -1 - 3 * a**2 + 4 * a**3)


def sf2(a, p):
    e = math.exp(-4 * a)
    return (e + a * a, -4 * e + 2 * a)


def sf3(a, p):
    return (-math.sin(10 * a), -10 * math.cos(10 * a))


def wt(a, p):  # test_wolfe_terminate
    return (-a + 0.05 * (a * a), -1 + 0.05 * 2 * a)


def quad(a, p):  # p = (A, B, C): A a^2 + B a + C
    A, B, C = p
    return (A * a * a + B * a + C, 2 * A * a + B)


def shiftq(a, p):  # (a - c)^2, p = (c,)
    c = p[0]
    return ((a - c) * (a - c), 2 * (a - c))


def lin_neg(a, p):
    return (-a, -1.0)


def lin_pos(a, p):
    return (a, 1.0)


def inf_half(a, p):
    return (((a - 1) * (a - 1), 2 * (a - 1)) if a < 0.5 else (INF, INF))


def nan_half(a, p):
    return (((a - 1) * (a - 1), 2 * (a - 1)) if a < 0.5 else (NAN, NAN))


def nan_dphi(a, p):
    return ((a - 1) * (a - 1), 2 * (a - 1) if a == 0 else NAN)


def big_half(a, p):  # finite but huge: dcstep's cubic overflows (theta = -inf), step becomes NaN
    return (((a - 1) * (a - 1), 2 * (a - 1)) if a < 0.5 else (1e308, 1.0))


# Moré-Thuente (1994) section 5.
MT1_B = 2.0
MT2_B = 0.004
MT3_B, MT3_L = 0.01, 39


def mt1(a, p):
    return (-a / (a * a + MT1_B), (a * a - MT1_B) / ((a * a + MT1_B) * (a * a + MT1_B)))


def mt2(a, p):
    x = a + MT2_B
    return (x**5 - 2 * x**4, 5 * x**4 - 8 * x**3)


def _mt3_p0(a):  # smoothed |a - 1|, eq. (5.3)
    if a <= 1 - MT3_B:
        return 1 - a
    if a >= 1 + MT3_B:
        return a - 1
    return (a - 1) * (a - 1) / (2 * MT3_B) + MT3_B / 2


def _mt3_d0(a):
    if a <= 1 - MT3_B:
        return -1.0
    if a >= 1 + MT3_B:
        return 1.0
    return (a - 1) / MT3_B


def mt3(a, p):
    arg = MT3_L * math.pi * a / 2
    return (
        _mt3_p0(a) + 2 * (1 - MT3_B) / (MT3_L * math.pi) * math.sin(arg),
        _mt3_d0(a) + (1 - MT3_B) * math.cos(arg),
    )


def _yanai(b1, b2):
    def g(b):
        return math.sqrt(1 + b * b) - b

    def f(a, p):
        r1 = math.sqrt((1 - a) * (1 - a) + b2 * b2)
        r2 = math.sqrt(a * a + b1 * b1)
        return (g(b1) * r1 + g(b2) * r2, g(b1) * (a - 1) / r1 + g(b2) * a / r2)

    return f


mt4 = _yanai(1e-3, 1e-3)
mt5 = _yanai(1e-2, 1e-3)
mt6 = _yanai(1e-3, 1e-2)

FUNCS = {
    "sf1": sf1, "sf2": sf2, "sf3": sf3, "wt": wt, "quad": quad, "shiftq": shiftq,
    "lin_neg": lin_neg, "lin_pos": lin_pos, "inf_half": inf_half, "nan_half": nan_half,
    "nan_dphi": nan_dphi, "big_half": big_half,
    "mt1": mt1, "mt2": mt2, "mt3": mt3, "mt4": mt4, "mt5": mt5, "mt6": mt6,
}  # fmt: skip


def closed(fn, params=()):
    f = FUNCS[fn]
    return (lambda a: f(float(a), params)[0]), (lambda a: f(float(a), params)[1])


