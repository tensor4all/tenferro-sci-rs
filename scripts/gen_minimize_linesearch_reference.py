divergences: list[tuple[str, str, str, str, str]] = []


def compare(cid, a, b, why):
    """a = scipy run, b = closed run."""
    for key in ("reason", "phi_evals", "dphi_evals", "n_trials"):
        if a[key] != b[key]:
            divergences.append((cid, key, str(a[key]), str(b[key]), why))
    sa, sb = a["stp"], b["stp"]
    if (sa == "none") != (sb == "none"):
        divergences.append((cid, "stp", sa, sb, why))
    elif sa != "none":
        x, y = float(sa), float(sb)
        if abs(x - y) > 1e-12 * max(abs(x), abs(y)):
            divergences.append((cid, "stp", sa, sb, why))


def scipy_test_cases():
    # --- test_scalar_search_wolfe1: 3 functions x 3 old_phi0 (global RNG, as pytest sets it up)
    t = TestLineSearch()
    t.setup_method()
    closed_params = {"_scalar_func_1": "sf1", "_scalar_func_2": "sf2", "_scalar_func_3": "sf3"}
    k = 0
    for name, phi, derphi, old_phi0 in t.scalar_iter():
        fn = closed_params[name]
        cid = f"sw1_{fn}_{k % 3}"
        old = float(old_phi0)
        a = wolfe1(cid + ".scipy", "scipy", "scipy_scalar", fn, (), phi, derphi, phi(0), old, derphi(0))
        cphi, cdphi = closed(fn)
        p0, d0 = FUNCS[fn](0.0, ())
        b = wolfe1(cid + ".closed", "closed", "scipy_scalar", fn, (), cphi, cdphi, p0, old, d0)
        compare(cid, a, b, "numpy exp/sin/pow vs libm")
        k += 1

    # --- test_line_search_wolfe1: 2 functions x 9 seeded (x, p), amax = 100
    t = TestLineSearch()
    t.setup_method()
    A = t.A
    k = 0
    for name, f, fprime, x, p, old_f in t.line_iter():
        fn = name.replace("_line_func_", "line")
        cid = f"lw1_{fn}_{k % 9}"
        f0 = f(x)
        g0 = fprime(x)
        s, fc, gc, fv, ofv, gv = ls.line_search_wolfe1(f, fprime, x, p, g0, f0, old_f, amax=100)
        a = record(cid + ".scipy", "scipy", "wolfe1", "scipy_line", fn, (), float(old_f))
        assert fc == a["phi_evals"] == gc  # sanity: our counts are SciPy's own
        # the line function along x + alpha p as the quadratic A a^2 + B a + C
        if fn == "line1":
            qa, qb, qc = float(p @ p), float(2 * (x @ p)), float(x @ x)
        else:
            qa, qb, qc = float(p @ A @ p), float(x @ A @ p + p @ A @ x), float(x @ A @ x + 1)
        params = (qa, qb, qc)
        cphi, cdphi = closed("quad", params)
        b = wolfe1(cid + ".closed", "closed", "scipy_line", "quad", params, cphi, cdphi,
                   qc, float(old_f), qb, amax=100.0)  # fmt: skip
        compare(cid, a, b, "BLAS dot products vs quadratic coefficients")
        k += 1

    # --- test_wolfe_terminate: phi = -s + 0.05 s^2, phi0 and dphi0 passed, old_phi0 None
    phi, dphi = closed("wt")
    wolfe1("wt.closed", "closed", "scipy_wolfe_terminate", "wt", (), phi, dphi, 0.0, None, -1.0)


def driver_cases():
    """Edge cases through scalar_search_wolfe1."""
    def go(cid, group, fn, params, phi0, old_phi0, dphi0, note="", **kw):
        phi, dphi = closed(fn, params)
        p0, d0 = FUNCS[fn](0.0, params)
        return wolfe1(cid, "closed", group, fn, params, phi, dphi,
                      p0 if phi0 else None, old_phi0, d0 if dphi0 else None, note=note, **kw)  # fmt: skip

    # initial-step heuristic: alpha1 = min(1, 1.01*2*(phi0-old)/dphi0), negative -> 1
    go("init_step_lt1", "init", "sf2", (), True, 1.1, True, "alpha1 = 0.0505 < 1")
    go("init_step_neg", "init", "sf2", (), True, 0.5, True, "alpha1 < 0 -> 1")
    # None phi0/dphi0: the driver evaluates phi(0), dphi(0) itself; counts include them
    go("none_inputs", "init", "sf1", (), False, None, False, "phi_evals = trials + 1")
    # descent / start errors
    go("not_descent", "edge", "lin_pos", (), True, None, True, "dphi0 > 0: no trial evaluation")
    go("above_stpmax", "edge", "shiftq", (5.0,), True, None, True, "alpha1 = 1 > amax = 1e-3", amax=1e-3)
    # monotone phi: STPMAX
    go("monotone_stpmax", "edge", "lin_neg", (), True, None, True, "trials 1, 5, 21, 50")
    # inf / NaN: the maintainer's decision on non-finite phi is open (issue #38, review 9.1).
    # SciPy's behaviour recorded here: inf -> bare WARN after 1 trial, NaN -> maxiter after 100.
    go("inf_half", "nonfinite", "inf_half", (), True, None, True, "OPEN QUESTION: SciPy = bare WARN, 1 trial")
    go("nan_half", "nonfinite", "nan_half", (), True, None, True, "OPEN QUESTION: SciPy = maxiter, 100 trials")
    go("nan_dphi_only", "nonfinite", "nan_dphi", (), True, None, True, "OPEN QUESTION: phi' NaN only")
    # finite phi where dcstep itself overflows: NonFiniteStep without any non-finite phi
    go("overflow_finite", "edge", "big_half", (), True, None, True, "phi = 1e308 is finite; theta overflows")


def dcsrch_cases():
    # maxiter = 2: trial 2 (alpha = 5) satisfies strong Wolfe but is never tested.
    r = dcsrch("maxiter2", "edge", "shiftq", (20.0,), 1e-4, 0.9, 1.0, maxiter=2, stpmax=50.0, stpmin=1e-8,
               note="last evaluated point is never tested")  # fmt: skip
    assert r["reason"] == "maxiter" and r["n_trials"] == 2
    a2, f2, g2 = [t for t in TRIALS if t[0] == "maxiter2"][-1][2:]
    f0, g0 = FUNCS["shiftq"](0.0, (20.0,))
    assert f2 <= f0 + 1e-4 * a2 * g0 and abs(g2) <= 0.9 * abs(g0), "trial 2 should satisfy strong Wolfe"
    dcsrch("maxiter3", "edge", "shiftq", (20.0,), 1e-4, 0.9, 1.0, maxiter=3, stpmax=50.0, stpmin=1e-8,
           note="same problem with one more iteration converges")  # fmt: skip
    # alpha0 = amax on (a-5)^2: STPMAX after one trial
    dcsrch("amax_eq_alpha0", "edge", "shiftq", (5.0,), 1e-4, 0.9, 1e-3, stpmax=1e-3, stpmin=1e-8,
           note="amax = 1e-3 = alpha0")  # fmt: skip
    # CONVERGENCE overwrites the STPMAX warning (later tests in dcsrch win): at alpha = stpmax = 4
    # both hold (f <= ftest, g <= gtest and |g| <= gtol |g0|)
    r = dcsrch("convergence_beats_stpmax", "edge", "shiftq", (5.0,), 1e-4, 0.9, 4.0, stpmax=4.0, stpmin=1e-8,
               note="alpha = stpmax and strong Wolfe: converged wins")  # fmt: skip
    assert r["reason"] == "converged" and r["n_trials"] == 1
    dcsrch("below_stpmin", "edge", "shiftq", (5.0,), 1e-4, 0.9, 1e-9, stpmin=1e-8, stpmax=50.0,
           note="alpha0 < stpmin")  # fmt: skip

    # --- reasons found by a small deterministic search; first candidate reaching the target wins
    def search(label, target, candidates):
        for i, c in enumerate(candidates):
            fn, params, ftol, gtol, a0, kw = c
            dcsrch(f"search_{label}_probe", "search", fn, params, ftol, gtol, a0, **kw)
            row = CASES[-1]
            n = row["n_trials"]
            del CASES[-1]
            del TRIALS[len(TRIALS) - n:]
            if row["reason"] == target:
                dcsrch(f"search_{label}", "search", fn, params, ftol, gtol, a0, note=f"candidate {i}", **kw)
                print(f"  search {label}: candidate {i} {c}")
                return
        raise SystemExit(f"search for {label} found nothing")

    search("stpmin", "stpmin",
           [("quad", (1e6, -1.0, 0.0), 1e-4, 0.9, 1.0, dict(stpmin=1e-3, stpmax=50.0)),
            ("quad", (1e8, -1.0, 0.0), 1e-4, 0.9, 1.0, dict(stpmin=1e-3, stpmax=50.0))])  # fmt: skip
    search("xtol", "xtol",
           [(fn, (), ft, gt, a0, dict(xtol=0.1))
            for fn in ("mt2", "mt3", "mt1") for a0 in (1e-3, 1.0, 1e3) for ft, gt in ((1e-4, 1e-12), (1e-4, 0.0))])  # fmt: skip
    search("rounding", "rounding",
           [(fn, (), ft, gt, a0, dict(xtol=0.0))
            for fn in ("mt1", "mt2", "mt4", "mt6") for a0 in (1.0, 1e-3, 1e3) for ft, gt in ((1e-4, 0.0), (0.0, 0.0), (1e-4, 1e-14))])  # fmt: skip


