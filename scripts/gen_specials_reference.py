def mp_lgamma(x):
    if x > 0:
        return mp.loggamma(x)
    return mp.re(mp.loggamma(x))


FUNCS = {
    "gamma": (1, GAMMA_X, lambda x: mp.gamma(x), sc.gamma),
    "lgamma": (1, LGAMMA_X, mp_lgamma, sc.gammaln),
    "rgamma": (1, RGAMMA_X, lambda x: mp.rgamma(x), sc.rgamma),
    "digamma": (1, DIGAMMA_X, lambda x: mp.digamma(x), sc.digamma),
    "zeta": (2, ZETA_SQ, lambda s, q: mp.zeta(s, q), sc.zeta),
    "beta": (2, BETA_AB, lambda a, b: mp.beta(a, b), sc.beta),
    "lbeta": (2, LBETA_AB, lambda a, b: mp.log(abs(mp.beta(a, b))), sc.betaln),
}


def write_reference():
    DATA.mkdir(parents=True, exist_ok=True)
    for name, (nargs, points, mpf, scf) in FUNCS.items():
        cols = [f"a{i}_hi,a{i}_lo" for i in range(nargs)]
        lines = [HEADER, "# columns: " + ",".join(cols) + ",ref_hi,ref_lo,scipy\n"]
        for p in points:
            args = [arg(a) for a in (p if nargs > 1 else (p,))]
            ref = dd(stable(mpf, *[mpv(a) for a in args]))
            if all(lo == 0.0 for _, lo in args):
                with np.errstate(all="ignore"):
                    s = fmt(scf(*[hi for hi, _ in args]))
            else:
                s = ""
            row = [fmt(c) for a in args for c in a] + [fmt(ref[0]), fmt(ref[1]), s]
            lines.append(",".join(row) + "\n")
        (DATA / f"{name}.csv").write_text("".join(lines))


