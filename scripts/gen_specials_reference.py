def mp_log1pmx(x):
    if x <= -1:
        return None
    with mp.workprec(_ext(1, x)):
        return +(mp.log1p(x) - x)


def mp_xlogy(x, y):
    if x == 0 or y <= 0:
        return None
    return x * mp.log(y)


def mp_xlog1py(x, y):
    if x == 0 or y <= -1:
        return None
    with mp.workprec(_ext(1, y)):
        return +(x * mp.log1p(y))


def mp_logit(x):
    if not 0 < x < 1:
        return None
    with mp.workprec(_ext(1, x)):
        return +mp.log(x / (1 - x))


