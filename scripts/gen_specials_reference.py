def _hyp_real(f):
    """Wrap f so that a complex or undefined result gives None."""

    def g(*args):
        try:
            with mp.workprec(mp.mp.prec + _o_extra(*args)):
                v = f(*args)
        except (ValueError, ZeroDivisionError, mp.libmp.NoConvergence):
            return None
        if v is None or isinstance(v, mp.mpc):
            return None
        return v

    return g


