def write_special_values(only=None):
    path = DATA / "special_values.csv"
    if only and path.exists():
        # Keep the rows of the other functions; replace those of `only`.
        old = [l for l in path.read_text().splitlines(keepends=True) if l.split(",")[0] not in only]
        lines = old
    else:
        lines = [HEADER, "# columns: function,a0,a1,a2,a3,scipy  (exact non-finite or zero results)\n"]
    for name, f, cases in SPECIAL:
        if only and name not in only:
            continue
        for args in cases:
            with np.errstate(all="ignore"):
                v = float(f(*args))
            if math.isfinite(v) and v != 0.0:
                raise SystemExit(f"{name}{args} = {v} is not a special value")
            a = list(args) + [""] * (4 - len(args))
            lines.append(",".join([name] + [fmt(x) if x != "" else "" for x in a] + [fmt(v)]) + "\n")
    (DATA / "special_values.csv").write_text("".join(lines))


# --------------------------------------------------------------------------
# Constant tables for the precision-adaptive (generic) algorithms.
# --------------------------------------------------------------------------

NB = 30  # Bernoulli numbers B_2 .. B_60
NZ = 80  # zeta(k) - 1 for k = 2 ..= NZ
NT = 120  # Taylor coefficients of digamma around its zeros
NZ0 = 36  # Taylor coefficients of zeta(s) around s = 0 (radius 1; used for |s| < 0.1)


def rs_pair(v) -> str:
    hi, lo = dd(v)
    return f"({hi!r}, {lo!r})"


def write_tables():
    stirling = [mp.bernoulli(2 * k) / (2 * k * (2 * k - 1)) for k in range(1, NB + 1)]
    digamma = [mp.bernoulli(2 * k) / (2 * k) for k in range(1, NB + 1)]
    em = [mp.bernoulli(2 * k) / mp.factorial(2 * k) for k in range(1, NB + 1)]
    negroot = mp.findroot(mp.digamma, mp.mpf("-0.504083008264455409"))
    posroot = mp.findroot(mp.digamma, mp.mpf("1.4616321449683622"))
    zm1 = [mp.zeta(k) - 1 for k in range(2, NZ + 1)]

    def taylor(root):
        r = mpv(dd(root))
        return [mp.polygamma(n, r) / mp.factorial(n) for n in range(1, NT + 1)]

    def table(name, doc, vals):
        return [
            f"/// {doc}\n",
            f"pub(crate) const {name}: [(f64, f64); {len(vals)}] = [\n",
            *[f"    {rs_pair(v)},\n" for v in vals],
            "];\n\n",
        ]
    out = [
        "// @generated by scripts/gen_specials_reference.py -- do not edit.\n",
        f"// mpmath {mp.__version__}, prec 256, {datetime.date.today().isoformat()}.\n",
        "//! Double-double constant tables for the precision-adaptive algorithms.\n",
        "//!\n",
        "//! Each entry is a pair `(hi, lo)` with `hi + lo` the value rounded to double-double.\n",
        "\n",
        f"/// `B_{{2k}} / (2k (2k-1))` for `k = 1..={NB}` (Stirling series of `ln Γ`, DLMF 5.11.1).\n",
        f"pub(crate) const STIRLING: [(f64, f64); {NB}] = [\n",
        *[f"    {rs_pair(v)},\n" for v in stirling],
        "];\n\n",
        f"/// `B_{{2k}} / (2k)` for `k = 1..={NB}` (asymptotic series of ψ, DLMF 5.11.2).\n",
        f"pub(crate) const DIGAMMA_ASY: [(f64, f64); {NB}] = [\n",
        *[f"    {rs_pair(v)},\n" for v in digamma],
        "];\n\n",
        f"/// `B_{{2k}} / (2k)!` for `k = 1..={NB}` (Euler–Maclaurin tail of ζ(s, q), DLMF 25.11.6 / 2.10.1).\n",
        f"pub(crate) const EULER_MACLAURIN: [(f64, f64); {NB}] = [\n",
        *[f"    {rs_pair(v)},\n" for v in em],
        "];\n\n",
        *table("ZETA_M1", f"`ζ(k) - 1` for `k = 2..={NZ}` (DLMF 5.7.3).", zm1),
        *table(
            "DIGAMMA_POS_TAYLOR",
            f"`ψ⁽ⁿ⁾(r)/n!` for `n = 1..={NT}` at `r = DIGAMMA_POSROOT` (DLMF 5.15.1 / 25.11.12).",
            taylor(posroot),
        ),
        *table(
            "DIGAMMA_NEG_TAYLOR",
            f"`ψ⁽ⁿ⁾(r)/n!` for `n = 1..={NT}` at `r = DIGAMMA_NEGROOT`.",
            taylor(negroot),
        ),
        *table(
            "ZETA_TAYLOR0",
            f"`ζ⁽ⁿ⁾(0)/n!` for `n = 0..{NZ0}` (Taylor series of ζ(s) about 0, DLMF 25.2.1 / 25.6.1).",
            [mp.zeta(0, derivative=n) / mp.factorial(n) for n in range(NZ0)],
        ),
        "/// `√(2π)`.\n",
        f"pub(crate) const SQRT_2PI: (f64, f64) = {rs_pair(mp.sqrt(2 * mp.pi))};\n",
        "/// `ln √(2π)`.\n",
        f"pub(crate) const LN_SQRT_2PI: (f64, f64) = {rs_pair(mp.log(mp.sqrt(2 * mp.pi)))};\n",
        "/// `ln π`.\n",
        f"pub(crate) const LN_PI: (f64, f64) = {rs_pair(mp.log(mp.pi))};\n",
        "/// Euler's constant γ.\n",
        f"pub(crate) const EULER_GAMMA: (f64, f64) = {rs_pair(mp.euler)};\n",
        "/// Positive zero of ψ, rounded to double-double, and ψ at that rounded point.\n",
        f"pub(crate) const DIGAMMA_POSROOT: (f64, f64) = {rs_pair(posroot)};\n",
        f"pub(crate) const DIGAMMA_POSROOT_VAL: (f64, f64) = {rs_pair(mp.digamma(mpv(dd(posroot))))};\n",
        "/// Negative zero of ψ near -0.504, rounded to double-double, and ψ at that rounded point.\n",
        f"pub(crate) const DIGAMMA_NEGROOT: (f64, f64) = {rs_pair(negroot)};\n",
        f"pub(crate) const DIGAMMA_NEGROOT_VAL: (f64, f64) = {rs_pair(mp.digamma(mpv(dd(negroot))))};\n",
    ]
    (CRATE / "src" / "generic" / "tables.rs").write_text("".join(out))


