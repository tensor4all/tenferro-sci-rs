"""Generate the reference data and the double-double constant tables of the
`specials` crate.

Run from the repository root:

    uv run scripts/gen_specials_reference.py

Outputs (committed; regenerating them is a separate commit):

* crates/specials/tests/data/<function>.csv  -- reference values
* crates/specials/tests/data/special_values.csv  -- SciPy's non-finite / zero results
* crates/specials/src/generic/tables.rs  -- Bernoulli-number tables and constants

Every real number is written as a double-double pair `hi,lo` with
`hi = fl(v)` and `lo = fl(v - hi)`, computed in mpmath at 256 bits, so that the
Rust side reads it without a decimal parser. A row whose arguments all have
`lo == 0` is an f64 row; it also carries SciPy's value for parity. The other
rows exercise double-double inputs and are checked only against mpmath.
"""

